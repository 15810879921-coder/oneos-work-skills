import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = path.dirname(fileURLToPath(import.meta.url));
const kit = path.dirname(here);
const fonts = path.resolve(kit, '../fonts/jetbrains-mono');
const boundary = ".oneos-surface[data-oneos-runtime='1']";
const digest = (data) => createHash('sha256').update(data).digest('hex');

// Generated from the existing canon; do not create a second hand-maintained theme.
export function syncGenerated({ check = false } = {}) {
  const outputs = new Map();
  const sources = {};
  function read(file) {
    const data = fs.readFileSync(file);
    sources[path.relative(kit, file)] = digest(data);
    return data;
  }
  for (const name of ['patterns', 'query']) {
    const file = path.join(kit, 'patterns', `${name}.css`);
    const css = read(file).toString();
    const tree = postcss.parse(css, { from: file });
    // Confirmed PC corrections are opt-in: preserve the legacy host stylesheet.
    if (name === 'patterns') {
      const contractFile = path.join(here, 'pattern-contract.css');
      tree.append(postcss.parse(read(contractFile).toString(), { from: contractFile }).nodes);
    }
    tree.walkAtRules('import', (rule) => {
      if (name !== 'patterns' || !rule.params.includes('jetbrains-mono.css')) {
        throw new Error(`Unreviewed global import: ${rule.params}`);
      }
      rule.params = "'./fonts/runtime-mono.css'";
    });
    tree.walkRules((rule) => {
      if (rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) {
        throw new Error('Keyframes require explicit runtime namespacing');
      }
      // PostCSS splits selector lists while preserving :is/:where commas.
      rule.selectors = rule.selectors.map((selector) => {
        if (!selector.startsWith('.oneos-')) {
          throw new Error(`Review selector before exporting: ${selector}`);
        }
        return /^\.oneos-surface(?=[\s.:[>#~+]|$)/.test(selector)
          ? selector.replace(/^\.oneos-surface/, boundary)
          : `${boundary} ${selector}`;
      });
    });
    tree.walkDecls('--oneos-font-data', (decl) => {
      decl.value = decl.value.replace("'JetBrains Mono'", "'OneOS Runtime Mono'");
    });
    outputs.set(`${name}.scoped.css`, `/* Generated by sync-generated.mjs from patterns/${name}.css; sha256=${digest(css)}. */\n${tree.toString()}`);
  }
  const theme = read(path.join(kit, 'antd-theme.ts')).toString();
  outputs.set('base-theme.ts', `// Generated from ../antd-theme.ts; sha256=${digest(theme)}. Do not edit.\n${theme}`);
  const fontTree = postcss.parse(read(path.join(fonts, 'jetbrains-mono.css')).toString());
  fontTree.walkDecls('font-family', (decl) => { decl.value = "'OneOS Runtime Mono'"; });
  outputs.set('fonts/runtime-mono.css', `/* Generated font alias; only the opt-in runtime references this family. */\n${fontTree.toString()}`);
  for (const name of fs.readdirSync(fonts).filter((name) => /\.woff2$|^OFL\.txt$/.test(name)).sort()) {
    outputs.set(`fonts/${name}`, read(path.join(fonts, name)));
  }
  outputs.set('generated-sources.json', JSON.stringify({ schemaVersion: 1, sources }, null, 2) + '\n');
  const stale = [];
  for (const [name, data] of outputs) {
    const destination = path.join(here, name);
    const bytes = Buffer.from(data);
    if (fs.existsSync(destination) && fs.readFileSync(destination).equals(bytes)) continue;
    stale.push(name);
    if (!check) {
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, bytes);
    }
  }
  if (check && stale.length) throw new Error(`Stale generated runtime files: ${stale.join(', ')}`);
  return { checked: outputs.size, updated: check ? [] : stale, sources };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = syncGenerated({ check: process.argv.includes('--check') });
  console.log(JSON.stringify({ checked: result.checked, updated: result.updated }));
}
